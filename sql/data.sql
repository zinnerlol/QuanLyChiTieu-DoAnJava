-- ---------------------------------------------------------------------
-- 1. NGƯỜI DÙNG
-- ---------------------------------------------------------------------
CREATE TABLE nguoi_dung (
    id            INT           NOT NULL IDENTITY(1,1),
    ho_ten        NVARCHAR(100) NOT NULL,
    email         NVARCHAR(150) NOT NULL UNIQUE,      -- UNIQUE: không trùng email
    mat_khau      NVARCHAR(255) NOT NULL,             -- lưu mật khẩu đã mã hóa, không lưu mật khẩu thật
    ngay_tao      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

-- ---------------------------------------------------------------------
-- 2. VÍ
-- ---------------------------------------------------------------------
CREATE TABLE vi (
    id            INT           NOT NULL IDENTITY(1,1),
    nguoi_dung_id INT           NOT NULL,
    ten_vi        NVARCHAR(100) NOT NULL,             -- ví dụ: Tiền mặt, Vietcombank
    so_du_ban_dau DECIMAL(15,2) NOT NULL DEFAULT 0,   -- số tiền có sẵn lúc bắt đầu dùng
    PRIMARY KEY (id),
    FOREIGN KEY (nguoi_dung_id) REFERENCES nguoi_dung (id)
        ON DELETE CASCADE                             -- xóa người dùng thì xóa luôn ví của họ
);

-- ---------------------------------------------------------------------
-- 3. DANH MỤC
-- ---------------------------------------------------------------------
CREATE TABLE danh_muc (
    id            INT           NOT NULL IDENTITY(1,1),
    nguoi_dung_id INT           NOT NULL,
    ten_danh_muc  NVARCHAR(100) NOT NULL,             -- ví dụ: Ăn uống, Lương
    loai          NVARCHAR(3)   NOT NULL CHECK (loai IN ('thu','chi')),   -- chỉ được chọn 'thu' hoặc 'chi'
    PRIMARY KEY (id),
    FOREIGN KEY (nguoi_dung_id) REFERENCES nguoi_dung (id)
        ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 4. GIAO DỊCH
-- ---------------------------------------------------------------------
CREATE TABLE giao_dich (
    id             INT           NOT NULL IDENTITY(1,1),
    nguoi_dung_id  INT           NOT NULL,
    vi_id          INT           NOT NULL,            -- tiền lấy ra từ / cho vào ví nào
    danh_muc_id    INT           NOT NULL,            -- khoản này thuộc danh mục nào
    so_tien        DECIMAL(15,2) NOT NULL CHECK (so_tien > 0),   -- luôn là số dương
    ngay_giao_dich DATE          NOT NULL,
    ghi_chu        NVARCHAR(255) NULL,                -- NULL: được để trống
    PRIMARY KEY (id),
    FOREIGN KEY (nguoi_dung_id) REFERENCES nguoi_dung (id) ON DELETE CASCADE,
    FOREIGN KEY (vi_id)         REFERENCES vi (id)         ON DELETE NO ACTION,   -- ví còn giao dịch thì không cho xóa
    FOREIGN KEY (danh_muc_id)   REFERENCES danh_muc (id)   ON DELETE NO ACTION    -- danh mục còn giao dịch thì không cho xóa
);

-- ---------------------------------------------------------------------
-- 5. NGÂN SÁCH
-- ---------------------------------------------------------------------
CREATE TABLE ngan_sach (
    id            INT           NOT NULL IDENTITY(1,1),
    nguoi_dung_id INT           NOT NULL,
    danh_muc_id   INT           NOT NULL,
    han_muc       DECIMAL(15,2) NOT NULL CHECK (han_muc > 0),    -- số tiền tối đa được chi
    thang         TINYINT       NOT NULL CHECK (thang BETWEEN 1 AND 12),
    nam           SMALLINT      NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (nguoi_dung_id, danh_muc_id, thang, nam),             -- mỗi danh mục chỉ có 1 ngân sách mỗi tháng
    -- SQL Server không cho 2 đường CASCADE cùng đi từ nguoi_dung tới ngan_sach,
    -- nên dòng dưới dùng NO ACTION (khi xóa người dùng, ngân sách vẫn bị xóa qua danh_muc)
    FOREIGN KEY (nguoi_dung_id) REFERENCES nguoi_dung (id) ON DELETE NO ACTION,
    FOREIGN KEY (danh_muc_id)   REFERENCES danh_muc (id)   ON DELETE CASCADE
);
GO

