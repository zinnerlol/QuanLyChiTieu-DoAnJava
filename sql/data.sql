-- CSDL QUẢN LÝ CHI TIÊU (BẢN ĐƠN GIẢN, DÀNH CHO NGƯỜI MỚI)
-- SQL Server (chạy trên SQL Server Management Studio)
-- =====================================================================
-- Gồm 5 bảng:
--   1. nguoi_dung : ai đang dùng ứng dụng
--   2. vi         : tiền đang nằm ở đâu (tiền mặt, ngân hàng, MoMo...)
--   3. danh_muc   : khoản tiền thuộc loại gì (ăn uống, lương...)
--   4. giao_dich  : mỗi lần thu hoặc chi tiền
--   5. ngan_sach  : hạn mức chi tối đa cho mỗi danh mục theo tháng
--
-- Quan hệ (mũi tên "->" nghĩa là "thuộc về"):
--   vi        -> nguoi_dung
--   danh_muc  -> nguoi_dung
--   giao_dich -> nguoi_dung, vi, danh_muc
--   ngan_sach -> nguoi_dung, danh_muc
-- =====================================================================

